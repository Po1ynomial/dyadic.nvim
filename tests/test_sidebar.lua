local H = dofile("tests/helpers.lua")
local eq, ok = H.eq, H.ok
local T = H.suite()
local api = vim.api
local Composer = require("dyadic.composer")
local Sidebar = require("dyadic.sidebar")

-- Under `nvim -l` a new 'columns' reaches the window layout only once it is recomputed.
local function screen(columns)
  vim.o.columns = columns
  vim.cmd("wincmd =")
  api.nvim_exec_autocmds("VimResized", {})
end

local function open(config)
  screen(160)
  return H.open(nil, config)
end

T("the sidebar holds the history and its composer at the right edge", function()
  local main = api.nvim_get_current_win()
  local agent = open()
  local win = Sidebar.window()
  eq(api.nvim_win_get_buf(win), agent.history_buf)
  eq(api.nvim_win_get_position(win)[2] + api.nvim_win_get_width(win), 160)
  eq(api.nvim_win_get_width(win), 56)
  eq(Composer.anchor(agent), win)
  eq(api.nvim_get_current_win(), Composer.window(agent))
  eq(vim.wo[win].winfixbuf, true)
  eq(vim.wo[win].winfixwidth, true)
  ok(api.nvim_win_is_valid(main), "the main window was replaced")
end)

T("the sidebar side is configurable", function()
  local agent = open({ sidebar = { side = "left" } })
  eq(api.nvim_win_get_position(Composer.anchor(agent))[2], 0)
end)

T("toggle hides and shows the sidebar; the agent keeps running", function()
  local agent = open()
  require("dyadic").command("toggle")
  eq(Sidebar.window(), nil)
  eq(vim.fn.win_findbuf(agent.history_buf), {})
  eq(agent.closed, false)
  require("dyadic").command("toggle")
  eq(api.nvim_win_get_buf(Sidebar.window()), agent.history_buf)
  eq(api.nvim_get_current_win(), Composer.window(agent))
end)

T("a new agent replaces the one in the sidebar", function()
  local first = open()
  first:set_draft("kept")
  local win = Sidebar.window()
  require("dyadic").command("new")
  H.wait(function()
    return #require("dyadic").list() == 2
  end)
  local second = require("dyadic").list()[2]
  eq(Sidebar.window(), win)
  eq(api.nvim_win_get_buf(win), second.history_buf)
  eq(Composer.window(first), nil)
  eq(Composer.anchor(second), win)
  eq(first:get_draft(), "kept")
  eq(first.closed, false)
end)

T("the width keeps a manual resize as a ratio within limits", function()
  open()
  local win = Sidebar.window()
  api.nvim_set_current_win(win)
  vim.cmd("vertical resize 120")
  H.settle()
  eq(api.nvim_win_get_width(win), 120)
  screen(120)
  H.settle()
  -- Three quarters of 120 is 90, but the main area keeps 40 columns.
  eq(api.nvim_win_get_width(win), 79)
  screen(400)
  H.settle()
  eq(api.nvim_win_get_width(win), 120)
end)

T("the sidebar refuses other buffers and opens files in the main area", function()
  local agent = open()
  local main = Sidebar.main_window()
  local dir = vim.fn.tempname()
  vim.fn.mkdir(dir .. "/src", "p")
  vim.fn.writefile({ "one", "two", "three" }, dir .. "/src/a.lua")
  agent.cwd = dir
  local win = Sidebar.window()
  api.nvim_set_current_win(win)
  eq(pcall(vim.cmd.edit, dir .. "/src/a.lua"), false)
  -- Put a path into the history the way tool output would show it.
  vim.bo[agent.history_buf].modifiable = true
  api.nvim_buf_set_lines(agent.history_buf, -1, -1, false, { "see src/a.lua:3" })
  vim.bo[agent.history_buf].modifiable = false
  api.nvim_win_set_cursor(win, { api.nvim_buf_line_count(agent.history_buf), 5 })
  H.keys("gF")
  eq(api.nvim_get_current_win(), main)
  eq(api.nvim_buf_get_name(0), vim.fs.normalize(vim.uv.fs_realpath(dir) .. "/src/a.lua"))
  eq(api.nvim_win_get_cursor(0)[1], 3)
  eq(api.nvim_win_get_buf(win), agent.history_buf)
end)

T("windows split inside the sidebar move to the main area", function()
  local agent = open()
  require("dyadic").command("toggle")
  require("dyadic").command("toggle")
  api.nvim_win_close(Composer.window(agent), true)
  H.settle()
  local win = Sidebar.window()
  api.nvim_set_current_win(win)
  vim.cmd("split")
  local split = api.nvim_get_current_win()
  H.settle()
  ok(not Sidebar.contains(split), "the split stayed in the sidebar")
  eq(api.nvim_win_get_width(win), 56)
  eq(api.nvim_win_get_position(win)[2] + api.nvim_win_get_width(win), 160)
end)

T(":q on the last window outside the sidebar closes the tab", function()
  open()
  vim.cmd("tabnew")
  vim.cmd("tabprevious")
  api.nvim_set_current_win(Sidebar.main_window())
  vim.cmd("quit")
  H.settle()
  eq(#api.nvim_list_tabpages(), 1)
end)

T("each tab has its own sidebar; the composer follows the agent", function()
  local agent = open()
  local first = Sidebar.window()
  vim.cmd("tabnew")
  require("dyadic").command("")
  H.settle()
  local second = Sidebar.window()
  ok(second ~= first and api.nvim_win_is_valid(first), "sidebars are not per tab")
  eq(Composer.anchor(agent), second)
  eq(#vim.fn.win_findbuf(agent.composer_buf), 1)
end)

return T
