local H = dofile("tests/helpers.lua")
local eq, ok = H.eq, H.ok
local T = H.suite()
local api = vim.api
local Composer = require("dyadic.composer")
local Sidebar = require("dyadic.sidebar")

-- Under `nvim -l` a new 'columns' reaches the window layout only once it is recomputed.
local function screen(columns)
  vim.o.columns = columns
  vim.cmd("wincmd =")
  api.nvim_exec_autocmds("VimResized", {})
end

local function open(config)
  screen(160)
  return H.open(nil, config)
end

-- Ordinary windows of the current tab: the main area.
local function main_area()
  return vim.tbl_filter(function(win)
    return api.nvim_win_get_config(win).relative == "" and not Sidebar.contains(win)
  end, api.nvim_tabpage_list_wins(0))
end

T("the sidebar holds the history and its composer at the right edge", function()
  local main = api.nvim_get_current_win()
  local agent = open()
  local win = Sidebar.window()
  eq(api.nvim_win_get_buf(win), agent.history_buf)
  eq(api.nvim_win_get_position(win)[2] + api.nvim_win_get_width(win), 160)
  eq(api.nvim_win_get_width(win), 56)
  eq(Composer.anchor(agent), win)
  eq(api.nvim_get_current_win(), win)
  eq(vim.wo[win].winfixbuf, true)
  eq(vim.wo[win].winfixwidth, true)
  ok(api.nvim_win_is_valid(main), "the main window was replaced")
end)

T("the sidebar side is configurable", function()
  local agent = open({ sidebar = { side = "left" } })
  eq(api.nvim_win_get_position(Composer.anchor(agent))[2], 0)
end)

T("toggle hides and shows the sidebar; the agent keeps running", function()
  vim.cmd("vsplit")
  local main = api.nvim_get_current_win()
  local agent = open()
  require("dyadic").command("toggle")
  eq(Sidebar.window(), nil)
  eq(vim.fn.win_findbuf(agent.history_buf), {})
  eq(agent.closed, false)
  -- Back to the main area's window used last.
  eq(api.nvim_get_current_win(), main)
  require("dyadic").command("toggle")
  eq(api.nvim_win_get_buf(Sidebar.window()), agent.history_buf)
  eq(api.nvim_get_current_win(), Sidebar.window())
end)

T("toggle from the main area goes into a visible sidebar", function()
  local agent = open()
  local main = Sidebar.main_window()
  api.nvim_set_current_win(main)
  require("dyadic").command("toggle")
  eq(api.nvim_get_current_win(), Sidebar.window())
  -- The window of the pair used last comes back, after hiding too.
  api.nvim_set_current_win(Composer.window(agent))
  api.nvim_set_current_win(main)
  require("dyadic").command("toggle")
  eq(api.nvim_get_current_win(), Composer.window(agent))
  require("dyadic").command("toggle")
  eq(api.nvim_get_current_win(), main)
  require("dyadic").show()
  eq(api.nvim_get_current_win(), Composer.window(agent))
end)

T("a new agent replaces the one in the sidebar", function()
  local first = open()
  first:set_draft("kept")
  local win = Sidebar.window()
  require("dyadic").command("")
  H.wait(function()
    return #require("dyadic").list() == 2
  end)
  local second = require("dyadic").list()[2]
  eq(Sidebar.window(), win)
  eq(api.nvim_win_get_buf(win), second.history_buf)
  eq(Composer.window(first), nil)
  eq(Composer.anchor(second), win)
  eq(first:get_draft(), "kept")
  eq(first.closed, false)
end)

T("the width keeps a manual resize as a ratio within limits", function()
  open()
  local win = Sidebar.window()
  -- Entering the window runs the layout check; headless Neovim has no WinResized.
  api.nvim_set_current_win(Sidebar.main_window())
  api.nvim_set_current_win(win)
  vim.cmd("vertical resize 120")
  H.settle()
  eq(api.nvim_win_get_width(win), 120)
  screen(120)
  H.settle()
  -- Three quarters of 120 is 90, but the main area keeps 40 columns.
  eq(api.nvim_win_get_width(win), 79)
  screen(400)
  H.settle()
  eq(api.nvim_win_get_width(win), 120)
end)

T("the sidebar refuses other buffers and opens files in the main area", function()
  local agent = open()
  local main = Sidebar.main_window()
  local dir = vim.fn.tempname()
  vim.fn.mkdir(dir .. "/src", "p")
  vim.fn.writefile({ "one", "two", "three" }, dir .. "/src/a.lua")
  agent.cwd = dir
  local win = Sidebar.window()
  api.nvim_set_current_win(win)
  eq(pcall(vim.cmd.edit, dir .. "/src/a.lua"), false)
  -- Put a path into the history the way tool output would show it.
  vim.bo[agent.history_buf].modifiable = true
  api.nvim_buf_set_lines(agent.history_buf, -1, -1, false, { "see src/a.lua:3" })
  vim.bo[agent.history_buf].modifiable = false
  api.nvim_win_set_cursor(win, { api.nvim_buf_line_count(agent.history_buf), 5 })
  H.keys("gF")
  eq(api.nvim_get_current_win(), main)
  eq(api.nvim_buf_get_name(0), vim.fs.normalize(vim.uv.fs_realpath(dir) .. "/src/a.lua"))
  eq(api.nvim_win_get_cursor(0)[1], 3)
  eq(api.nvim_win_get_buf(win), agent.history_buf)
end)

T("windows split inside the sidebar move to the main area; splits of it are undone", function()
  local agent = open()
  local win = Sidebar.window()
  api.nvim_set_current_win(win)
  vim.cmd("vnew")
  local split = api.nvim_get_current_win()
  H.settle()
  ok(not Sidebar.contains(split), "the split stayed in the sidebar")
  eq(api.nvim_win_get_width(win), 56)
  eq(api.nvim_win_get_position(win)[2] + api.nvim_win_get_width(win), 160)
  local wins = api.nvim_list_wins()
  api.nvim_set_current_win(win)
  vim.cmd("vsplit")
  H.settle()
  eq(api.nvim_list_wins(), wins)
  eq(api.nvim_get_current_win(), win)
  eq(api.nvim_win_get_width(win), 56)
  eq(Composer.anchor(agent), win)
end)

T("closing the sidebar's composer closes the sidebar", function()
  local agent = open()
  vim.cmd("close")
  H.settle()
  eq(Sidebar.window(), nil)
  eq(vim.fn.win_findbuf(agent.history_buf), {})
end)

T("the history shown in the main area goes to the sidebar instead", function()
  local file = vim.fn.tempname() .. ".txt"
  vim.fn.writefile({ "x" }, file)
  vim.cmd("edit " .. file)
  local buf, main = api.nvim_get_current_buf(), api.nvim_get_current_win()
  local agent = open()
  require("dyadic").command("toggle")
  H.settle()
  eq(Sidebar.window(), nil)
  api.nvim_set_current_win(main)
  vim.cmd("buffer " .. agent.history_buf)
  H.settle()
  eq(api.nvim_win_get_buf(main), buf)
  eq(api.nvim_win_get_buf(Sidebar.window()), agent.history_buf)
  eq(Composer.anchor(agent), Sidebar.window())
  eq(#vim.fn.win_findbuf(agent.history_buf), 1)
end)

T(":only in the sidebar's composer keeps the sidebar", function()
  local agent = open()
  vim.cmd("only")
  H.settle()
  local win = Sidebar.window()
  ok(win, "no sidebar")
  eq(Composer.anchor(agent), win)
  eq(vim.wo[win].winfixbuf, true)
  eq(api.nvim_win_get_width(win), 56)
  eq(#main_area(), 1)
end)

T(":q on the last window outside the sidebar closes the tab", function()
  open()
  vim.cmd("tabnew")
  vim.cmd("tabprevious")
  api.nvim_set_current_win(Sidebar.main_window())
  vim.cmd("quit")
  H.settle()
  eq(#api.nvim_list_tabpages(), 1)
end)

T("the sidebar never stands alone: a closed main area comes back with the last file", function()
  local file = vim.fn.tempname() .. ".txt"
  vim.fn.writefile({ "x" }, file)
  vim.cmd("edit " .. file)
  local buf = api.nvim_get_current_buf()
  local agent = open()
  for _, how in ipairs({ "close", "only in the sidebar", "api" }) do
    if how == "close" then
      api.nvim_set_current_win(Sidebar.main_window())
      vim.cmd("close")
    elseif how == "only in the sidebar" then
      api.nvim_set_current_win(Sidebar.window())
      vim.cmd("only")
    else
      api.nvim_win_close(Sidebar.main_window(), true)
    end
    H.settle()
    local area = main_area()
    eq(#area, 1, how)
    eq(api.nvim_win_get_buf(area[1]), buf, how)
    eq(api.nvim_win_get_position(area[1])[2], 0, how)
    -- The sidebar keeps its place and width.
    eq(api.nvim_win_get_buf(Sidebar.window()), agent.history_buf, how)
    eq(api.nvim_win_get_width(Sidebar.window()), 56, how)
  end
end)

T("a left sidebar gets its main area back on the right", function()
  open({ sidebar = { side = "left" } })
  api.nvim_set_current_win(Sidebar.main_window())
  vim.cmd("close")
  H.settle()
  local area = main_area()
  eq(#area, 1)
  eq(api.nvim_win_get_position(Sidebar.window())[2], 0)
  eq(api.nvim_win_get_position(area[1])[2], 57)
end)

T("a closed main area in another tab comes back in that tab", function()
  open()
  local tab = api.nvim_get_current_tabpage()
  local main = Sidebar.main_window()
  vim.cmd("tabnew")
  local other = api.nvim_get_current_tabpage()
  local windows = api.nvim_tabpage_list_wins(other)
  api.nvim_win_close(main, true)
  H.settle()
  eq(api.nvim_get_current_tabpage(), other)
  eq(api.nvim_tabpage_list_wins(other), windows)
  eq(#api.nvim_tabpage_list_wins(tab), 3)
  ok(api.nvim_win_is_valid(Sidebar.main_window(tab)))
end)

T("each tab has its own sidebar and composer window", function()
  local agent = open()
  local tab, first = api.nvim_get_current_tabpage(), Sidebar.window()
  vim.cmd("tabnew")
  require("dyadic").show()
  H.settle()
  local second = Sidebar.window()
  ok(second ~= first and api.nvim_win_is_valid(first), "sidebars are not per tab")
  eq(Composer.anchor(agent), second)
  eq(Composer.anchor(agent, tab), first)
  eq(#vim.fn.win_findbuf(agent.composer_buf), 2)
  -- One draft, shown in both.
  agent:set_draft("shared")
  eq(api.nvim_buf_get_lines(api.nvim_win_get_buf(Composer.window(agent, tab)), 0, -1, false), { "shared" })
  vim.cmd("tabprevious")
  H.settle()
  eq(Sidebar.window(), first)
  eq(Composer.window(agent) ~= nil, true)
end)

return T
